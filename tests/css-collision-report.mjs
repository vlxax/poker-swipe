import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const TARGETS = [
  '#profileArea', '#dailyArea', '#polyana', '#psPolyanaArea', '.screen', '.screen.active',
  '.hidden', '.card', '.nav', '.nav button', '#home', '.v32', '.v38', '.v39', '.psScreen', '.psCard', '.psBtn',
];

function collectCssFiles(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name === 'node_modules' || name === '.git') continue;
      collectCssFiles(p, acc);
    } else if (name.endsWith('.css')) acc.push(p);
  }
  return acc;
}

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

function rulesForSelector(css, selector) {
  const esc = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`(${esc}[^{,]*?)\\{([^}]*)\\}`, 'g');
  const hits = [];
  let m;
  while ((m = re.exec(css))) {
    hits.push({ selector: m[1].trim(), body: m[2].trim().slice(0, 120) });
  }
  return hits;
}

const files = collectCssFiles(ROOT);
const report = [];

for (const sel of TARGETS) {
  const matches = [];
  for (const file of files) {
    const css = stripComments(readFileSync(file, 'utf8'));
    const hits = rulesForSelector(css, sel);
    if (hits.length) matches.push({ file: file.replace(ROOT + '/', ''), count: hits.length, sample: hits[0] });
  }
  if (matches.length > 1) {
    report.push({
      selector: sel,
      files: matches.map((m) => m.file),
      collision: matches.length > 1,
      note: 'Winning rule = last linked stylesheet in index.html + specificity',
    });
  }
}

const md = [
  '# CSS Collision Report (static scan)',
  '',
  'Generated by `npm run test:css-collision`. Does not compute cascade winners — use for audit only.',
  '',
  '| Selector | Files defining rules | Collision |',
  '|----------|----------------------|-----------|',
  ...report.map((r) => `| \`${r.selector}\` | ${r.files.length} (${r.files.slice(0, 4).join(', ')}${r.files.length > 4 ? '…' : ''}) | yes |`),
  '',
  '## Intentional overlaps',
  '- `.screen.active` — screen enter motion in `ps-design-tokens.css` and `game-polish.css` (same keyframe name; last load wins partial props).',
  '- `.nav` — multiple versioned patches in `index.html` inline + v32 CSS; fixed bottom nav is intentional.',
  '',
];

writeFileSync(join(ROOT, 'CSS_COLLISION_REPORT.md'), md.join('\n'));
console.log(JSON.stringify({ pass: true, collisions: report.length, out: 'CSS_COLLISION_REPORT.md' }, null, 2));
